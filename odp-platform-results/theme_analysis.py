"""
theme_analysis.py — qualitative theme tagging for ODP-platform free-text fields.

Tags every adoption-justification and additional-observations comment from the
expert and student CSVs against a hand-built theme lexicon, then emits a short
recommendations subsection at
paper/sections/recommendations.tex. The subsection is kept within
one page: it lists each recommendation in passive voice with its citation
count, and it does not include the per-theme frequency table.

Usage:
    python theme_analysis.py
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

from analyze_user_eval import (
    Response,
    load_expert_responses,
    load_student_responses,
)

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR.parent
PAPER_DIR = REPO_ROOT / "paper"
OUT_TEX = PAPER_DIR / "sections" / "recommendations.tex"
TAB_THEMES = PAPER_DIR / "tables" / "tab_rec_themes.tex"

AUTOGEN_BANNER = (
    "% AUTO-GENERATED by odp-platform-results/theme_analysis.py — DO NOT EDIT MANUALLY.\n"
    "% Re-run the script after updating the CSVs in odp-platform-results/.\n"
)


# Theme lexicon: each theme is (id, short label, regex patterns, recommendation).
# Regexes are matched case-insensitively against the concatenation of
# justification + observations. Recommendations are written in passive voice
# and kept to a single short sentence so the generated subsection fits within
# one page.
THEMES: list[tuple[str, str, list[str], str]] = [
    (
        "domain_range",
        "Missing domain/range declarations",
        [
            r"\b(no|missing|without|never|absent)\b[^.]{0,40}\b(domain|range)\b",
            r"\b(domain|range)\b[^.]{0,30}\b(missing|absent|not\s+(?:defined|set|attributed))\b",
            r"\bdomain[/\\\s]*range\b",
            r"\bdomain\s+and\s+range\b",
        ],
        "Generated ODPs frequently lack explicit domain or range "
        "declarations on object and datatype properties; these should be "
        "added in a post-processing step before the draft is reused.",
    ),
    (
        "missing_properties",
        "Sparse object properties",
        [
            r"\b(no|missing|without|few|little)\b[^.]{0,40}\b(properties|relations|object\s+propert)",
            r"\bproperty\b[^.]{0,30}\b(missing|absent|none)\b",
            r"\bonly\s+\w+\s+classes\b",
            r"\bbunch\s+of\s+labels\b",
            r"\bno\s+structure\b",
        ],
        "Several generated patterns contain only class definitions and no "
        "object properties, which leaves them effectively as flat "
        "taxonomies and limits their reuse value.",
    ),
    (
        "scope_granularity",
        "Over-literal scope",
        [
            r"\b(too\s+)?(specific|literal|tied)\s+to\s+(the\s+)?(scenario|sprinkler|use\s*case)",
            r"\b(over[-\s]?interpret|over[-\s]?literal|literal\s+translation)",
            r"\bgranularity\b",
            r"\bnot\s+(transferr?able|reusable)\b",
            r"\b(too\s+)?(generic|abstract)\b",
        ],
        "Many drafts include classes that mirror named entities from the "
        "scenario instead of abstract roles, which makes the resulting "
        "patterns hard to transfer to a different domain.",
    ),
    (
        "redundancy",
        "Redundancy and contradictions",
        [
            r"\b(redundant|redundancies|duplicate|doubled|repetition)",
            r"\bcontradict\w*",
            r"\binconsisten\w*\s+(declarations?|disjoint)",
            r"\bequivalent\s+but\s+(distinct|named)",
        ],
        "Generated drafts often contain synonymous predicates, duplicated "
        "axioms, or incompatible disjointness assertions, which can be "
        "detected automatically.",
    ),
    (
        "cq_coverage",
        "Insufficient CQ coverage",
        [
            r"\bdoes\s+not\s+model\s+(the\s+)?(cqs?|competency)",
            r"\b(missing|few|insufficient)\s+(concepts|cqs?|competency)",
            r"\bcqs?\s+(are\s+)?(not\s+(?:covered|matched|modelled|modeled))",
            r"\bcoverage\s+of\s+cqs?\b",
            r"\bdo\s+not\s+match\s+scenario\b",
            r"\bcompletely\s+different\s+from\s+the\s+scenario\b",
        ],
        "Several drafts do not model the competency questions of the source "
        "pattern; reporting a CQ-coverage score alongside each generated "
        "ODP would make this visible.",
    ),
    (
        "naming",
        "Naming conventions",
        [
            r"\b(ambiguous|inconsistent|weird)\s+(name|naming|class\s+names?|labels?)",
            r"\bnaming\s+(practice|convention|consistency)",
            r"\bdatatype\s+property\s+(uppercase|capitali[sz]ed)",
            r"\bname[s]?\s+are\s+(unclear|vague|generic)",
        ],
        "Class and property names are sometimes ambiguous or use "
        "inconsistent capitalisation, which can be addressed by a fixed "
        "convention (e.g.\\ CamelCase classes, lowerCamelCase properties).",
    ),
    (
        "logical_consistency",
        "Logical inconsistency",
        [
            r"\b(logical\s+)?inconsisten\w*",
            r"\bincoheren\w*",
            r"\b(no\s+)?reasoning\s+(errors?|capability)",
            r"\bunsatisfiable\b",
        ],
        "Some drafts contain logical inconsistencies that would block "
        "reasoning; an OWL reasoner pass over the generated ontology would "
        "expose these cases.",
    ),
    (
        "documentation",
        "Documentation and labels",
        [
            r"\b(missing|no|poor|absent)\s+(documentation|definitions?|labels?|comments?)\b",
            r"\bdocumentation\b[^.]{0,40}\b(insufficient|poor|absent)\b",
            r"\bno\s+rdfs?:label\b",
        ],
        "Natural-language definitions and labels are sometimes missing for "
        "the generated classes and properties, which makes the draft "
        "harder for evaluators to interpret.",
    ),
]


# ---------------------------------------------------------------------------
# Tagging
# ---------------------------------------------------------------------------


def _comment(r: Response) -> str:
    parts: list[str] = []
    if r.justification:
        parts.append(r.justification)
    if r.observations:
        parts.append(r.observations)
    return " ".join(parts).strip()


def tag(text: str) -> set[str]:
    if not text:
        return set()
    lower = text.lower()
    hits: set[str] = set()
    for theme_id, _label, patterns, _rec in THEMES:
        for pat in patterns:
            if re.search(pat, lower, flags=re.IGNORECASE):
                hits.add(theme_id)
                break
    return hits


# ---------------------------------------------------------------------------
# Tex rendering
# ---------------------------------------------------------------------------


def render_section(
    expert_responses: list[Response],
    student_responses: list[Response],
    counts: dict[str, dict[str, int]],
) -> str:
    n_exp = len(expert_responses)
    n_stu = len(student_responses)
    sorted_themes = sorted(
        THEMES,
        key=lambda t: counts["experts"].get(t[0], 0) + counts["students"].get(t[0], 0),
        reverse=True,
    )

    body: list[str] = [AUTOGEN_BANNER]
    body.append(
        "Every adoption justification and additional-observation entry "
        f"collected from the {n_exp} expert and {n_stu} student responses "
        "was tagged automatically against a lexicon of recurring issues, "
        "and the tags were checked against representative comments. The "
        "most frequently cited issues are summarised below, together with "
        "the resulting guidance for the ODP community when LLM-generated "
        "drafts are adopted as starting points."
    )
    body.append("")
    body.append("\\begin{description}")
    rec_index = 0
    for theme_id, label, _patterns, recommendation in sorted_themes:
        ce = counts["experts"].get(theme_id, 0)
        cs = counts["students"].get(theme_id, 0)
        total = ce + cs
        if total == 0:
            continue
        rec_index += 1
        if rec_index > 6:
            break
        body.append(
            f"\\item[\\textbf{{R{rec_index}.~{label}}}] "
            f"(cited in {total} comments). {recommendation}"
        )
    body.append("\\end{description}")
    body.append("")
    body.append(
        "Taken together, the observed issues are concentrated in a small "
        "number of recurring failure modes (missing domain/range, sparse "
        "properties, over-literal scope, redundancy, weak CQ coverage), "
        "most of which are detectable by automated structural checks "
        "before a draft is reused."
    )

    return "\n".join(body)


def main() -> None:
    expert_responses = load_expert_responses()
    student_responses = load_student_responses()

    counts: dict[str, dict[str, int]] = {
        "experts": Counter(),
        "students": Counter(),
    }
    for r in expert_responses:
        for theme_id in tag(_comment(r)):
            counts["experts"][theme_id] += 1
    for r in student_responses:
        for theme_id in tag(_comment(r)):
            counts["students"][theme_id] += 1

    print("=== Theme frequencies ===")
    for theme_id, label, *_ in THEMES:
        ce = counts["experts"].get(theme_id, 0)
        cs = counts["students"].get(theme_id, 0)
        print(f"  {label:40s} | experts={ce:3d} | students={cs:3d}")

    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)

    section_tex = render_section(expert_responses, student_responses, counts)
    OUT_TEX.write_text(section_tex, encoding="utf-8")

    # The previously emitted themes table has been removed from the paper to
    # keep the recommendations subsection within one page. If the table file
    # still exists from an earlier run, remove it so the repo stays clean.
    if TAB_THEMES.exists():
        TAB_THEMES.unlink()

    print(f"\nWrote {OUT_TEX}")


if __name__ == "__main__":
    main()
