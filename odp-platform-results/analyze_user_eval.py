@dataclass
class Response:
    evaluator: str
    scenario_id: str
    track: str
    helpfulness: int | None
    reusability: int | None
    clarity: int | None
    adoption: str
    time_saved_label: str
    time_saved_pct: float | None
    justification: str
    observations: str

    @property
    def model(self) -> str:
        return CREATIVITY_MODEL if self.track == CREATIVITY else FUNCTIONALITY_MODEL

    @property
    def config(self) -> str:
        return CREATIVITY_CONFIG if self.track == CREATIVITY else FUNCTIONALITY_CONFIG


def _strip_bom(key: str) -> str:
    return key.lstrip("﻿").strip('"')


def _normalize_time_saved(raw: str) -> str:
    """Normalize en-dash variants and stray whitespace in time-saved labels."""
    s = unicodedata.normalize("NFKC", raw or "").strip()
    # Replace any unicode dash with ASCII '-'
    for dash in ("‐", "‑", "‒", "–", "—", "−"):
        s = s.replace(dash, "-")
    # Some encodings turn en-dash into '?' — make a best effort
    s = s.replace("?", "-")
    return s


def _parse_int(raw: str) -> int | None:
    raw = (raw or "").strip()
    if not raw:
        return None
    try:
        return int(raw)
    except ValueError:
        return None


def _parse_pattern_url(url: str) -> tuple[str, str, str]:
    parts = url.split("/")
    idx = parts.index("outputs")
    return parts[idx + 1], parts[idx + 2], parts[idx + 3]


def _classify_track(model: str, config: str) -> str | None:
    if model == CREATIVITY_MODEL and config == CREATIVITY_CONFIG:
        return CREATIVITY
    if model == FUNCTIONALITY_MODEL and config == FUNCTIONALITY_CONFIG:
        return FUNCTIONALITY
    return None


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh)
        rows = []
        for raw in reader:
            rows.append({_strip_bom(k): (v or "") for k, v in raw.items()})
    return rows


def load_expert_responses() -> list[Response]:
    """Merge external experts, paper-author CSVs, and author-extra rows as
    a single expert pool. Author CSVs use a hybrid schema: rows where the
    author rated their own pattern (intent_match populated) are excluded
    here, while rows where they rated a randomly assigned extra pattern
    (helpfulness populated) are included because they share the expert
    questionnaire."""
    out: list[Response] = []

    def _push(row: dict) -> None:
        try:
            model, config, scen = _parse_pattern_url(row["pattern_link"])
        except (ValueError, KeyError):
            return
        track = _classify_track(model, config)
        if track is None:
            return
        ts_label = _normalize_time_saved(row.get("q_q_time_saved", ""))
        out.append(
            Response(
                evaluator=row["evaluator_token"],
                scenario_id=scen,
                track=track,
                helpfulness=_parse_int(row.get("q_q_overall_helpfulness", "")),
                reusability=_parse_int(row.get("q_q_reusability", "")),
                clarity=_parse_int(row.get("q_q_clarity_documentation", "")),
                adoption=row.get("q_q_adoption_threshold", "").strip(),
                time_saved_label=ts_label,
                time_saved_pct=TIME_SAVED_MIDPOINT.get(ts_label),
                justification=row.get("q_q_adoption_justification", "").strip(),
                observations=row.get("q_q_additional_observations", "").strip(),
            )
        )

    for path in (EXPERT_CSV, US_CSV):
        for row in _read_csv(path):
            _push(row)

    # Fold the author-extra rows into the expert pool: skip rows where the
    # author was rating their own pattern (intent_match populated) or where
    # the submission looks like a test session (duration too short).
    for path in AUTHOR_CSVS:
        for row in _read_csv(path):
            if (row.get("q_q_intent_match", "") or "").strip():
                continue
            try:
                duration = int(row.get("duration_ms", "0") or 0)
            except ValueError:
                duration = 0
            if duration < AUTHOR_MIN_DURATION_MS:
                continue
            if not (row.get("q_q_overall_helpfulness", "") or "").strip():
                continue
            _push(row)

    return out


def load_student_responses() -> list[Response]:
    """Students use a different schema — we keep the dimensions that overlap."""
    out: list[Response] = []
    for row in _read_csv(STUDENTS_CSV):
        try:
            model, config, scen = _parse_pattern_url(row["pattern_link"])
        except (ValueError, KeyError):
            continue
        track = _classify_track(model, config)
        if track is None:
            continue
        ts_label = _normalize_time_saved(row.get("q_q_time_saved", ""))
        out.append(
            Response(
                evaluator=row["evaluator_token"],
                scenario_id=scen,
                track=track,
                helpfulness=None,
                reusability=None,
                clarity=_parse_int(row.get("q_q_documentation_clarity", "")),
                adoption=row.get("q_q_adoption", "").strip(),
                time_saved_label=ts_label,
                time_saved_pct=TIME_SAVED_MIDPOINT.get(ts_label),
                justification=row.get("q_q_adoption_justification", "").strip(),
                observations="",
            )
        )
    return out


# ---------------------------------------------------------------------------
# Krippendorff's alpha (self-contained, supports ordinal & nominal data)
# ---------------------------------------------------------------------------


def _build_units(values_per_unit: list[list[float | None]]) -> list[list[float]]:
    """Drop missing values, keep only units with >= 2 ratings."""
    return [
        [v for v in unit if v is not None]
        for unit in values_per_unit
        if sum(1 for v in unit if v is not None) >= 2
    ]


def _ordinal_distance(c1: float, c2: float, freq: dict[float, int]) -> float:
    if c1 == c2:
        return 0.0
    lo, hi = (c1, c2) if c1 < c2 else (c2, c1)
    n_g = sum(n for v, n in freq.items() if lo <= v <= hi)
    return float((n_g - (freq[lo] + freq[hi]) / 2.0) ** 2)


def _nominal_distance(c1: float, c2: float, _freq: dict[float, int]) -> float:
    return 0.0 if c1 == c2 else 1.0


def krippendorff_alpha(
    values_per_unit: list[list[float | None]], scale: str = "ordinal"
) -> tuple[float, int]:
    units = _build_units(values_per_unit)
    if not units:
        return float("nan"), 0
    distance = _ordinal_distance if scale == "ordinal" else _nominal_distance

    freq: dict[float, int] = defaultdict(int)
    for u in units:
        for v in u:
            freq[v] += 1
    if len(freq) < 2:
        return 1.0, len(units)

    observed = 0.0
    for u in units:
        m_u = len(u)
        if m_u < 2:
            continue
        weight = 1.0 / (m_u - 1)
        for i in range(m_u):
            for j in range(m_u):
                if i == j:
                    continue
                observed += weight * distance(u[i], u[j], freq)

    n_total = sum(freq.values())
    expected = 0.0
    keys = list(freq.keys())
    for c1 in keys:
        for c2 in keys:
            if c1 == c2:
                continue
            expected += freq[c1] * freq[c2] * distance(c1, c2, freq)
    expected /= n_total - 1 if n_total > 1 else 1

    if expected == 0:
        return 1.0, len(units)
    return 1.0 - observed / expected, len(units)


