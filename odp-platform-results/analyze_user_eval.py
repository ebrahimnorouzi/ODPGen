def _stats_block(values: Iterable[float]) -> dict[str, float | int]:
    vals = [v for v in values if v is not None]
    if not vals:
        return {"n": 0, "mean": float("nan"), "median": float("nan"), "sd": float("nan")}
    return {
        "n": len(vals),
        "mean": statistics.fmean(vals),
        "median": statistics.median(vals),
        "sd": statistics.stdev(vals) if len(vals) > 1 else 0.0,
    }


def likert_summary(responses: list[Response]) -> dict[str, dict[str, dict]]:
    out: dict[str, dict[str, dict]] = {}
    for dim, attr in (
        ("helpfulness", "helpfulness"),
        ("reusability", "reusability"),
        ("clarity", "clarity"),
    ):
        out[dim] = {}
        for track in (CREATIVITY, FUNCTIONALITY):
            vals = [getattr(r, attr) for r in responses if r.track == track]
            out[dim][track] = _stats_block(vals)
    return out


def mann_whitney(responses: list[Response]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for dim, attr in (
        ("helpfulness", "helpfulness"),
        ("reusability", "reusability"),
        ("clarity", "clarity"),
    ):
        a = [getattr(r, attr) for r in responses if r.track == CREATIVITY and getattr(r, attr) is not None]
        b = [getattr(r, attr) for r in responses if r.track == FUNCTIONALITY and getattr(r, attr) is not None]
        if not a or not b:
            out[dim] = {"U": float("nan"), "p": float("nan")}
            continue
        u, p = stats.mannwhitneyu(a, b, alternative="two-sided")
        out[dim] = {"U": float(u), "p": float(p)}
    return out


def adoption_summary(responses: list[Response]) -> dict[str, dict[str, int | float]]:
    out: dict[str, dict] = {}
    for track in (CREATIVITY, FUNCTIONALITY, "Overall"):
        sel = responses if track == "Overall" else [r for r in responses if r.track == track]
        c = Counter(r.adoption for r in sel)
        total = sum(c.values()) or 1
        ts_vals = [r.time_saved_pct for r in sel if r.time_saved_pct is not None]
        out[track] = {
            "yes": c.get("Yes", 0),
            "maybe": c.get("Maybe", 0),
            "no": c.get("No", 0),
            "total": sum(c.values()),
            "yes_pct": 100 * c.get("Yes", 0) / total,
            "maybe_pct": 100 * c.get("Maybe", 0) / total,
            "no_pct": 100 * c.get("No", 0) / total,
            "mean_time_saved": statistics.fmean(ts_vals) if ts_vals else float("nan"),
            "n_time_saved": len(ts_vals),
            "zero_time_pct": (
                100 * sum(1 for v in ts_vals if v == 0) / len(ts_vals) if ts_vals else float("nan")
            ),
        }
    return out


def iaa(responses: list[Response]) -> dict[str, dict[str, float]]:
    """
    Krippendorff's alpha computed on (pattern, track) units. Each unit
    aggregates the ratings given by different evaluators to the same
    (pattern, track) pair. Only units with >= 2 evaluators are retained.
    """
    units_by_dim: dict[str, list[list[float | None]]] = defaultdict(list)
    pattern_track = defaultdict(list)
    for r in responses:
        pattern_track[(r.scenario_id, r.track)].append(r)

    for key, group in pattern_track.items():
        if len(group) < 2:
            continue
        for dim, attr in (
            ("helpfulness", "helpfulness"),
            ("reusability", "reusability"),
            ("clarity", "clarity"),
        ):
            units_by_dim[dim].append([getattr(r, attr) for r in group])
        units_by_dim["adoption"].append(
            [{"Yes": 2.0, "Maybe": 1.0, "No": 0.0}.get(r.adoption) for r in group]
        )
        units_by_dim["time_saved"].append([r.time_saved_pct for r in group])

    out: dict[str, dict] = {}
    for dim in ("helpfulness", "reusability", "clarity", "time_saved"):
        alpha, n = krippendorff_alpha(units_by_dim[dim], scale="ordinal")
        out[dim] = {"alpha": alpha, "items": n, "scale": "ordinal"}
    alpha, n = krippendorff_alpha(units_by_dim["adoption"], scale="nominal")
    out["adoption"] = {"alpha": alpha, "items": n, "scale": "nominal"}
    return out


def per_pattern(responses: list[Response]) -> list[dict]:
    rows: list[dict] = []
    pattern_ids = sorted({r.scenario_id for r in responses})
    for pid in pattern_ids:
        row = {"scenario_id": pid, "title": PATTERN_TITLES.get(pid, pid)}
        for track in (CREATIVITY, FUNCTIONALITY):
            sel = [r for r in responses if r.scenario_id == pid and r.track == track]
            n = len(sel)
            help_mean = (
                statistics.fmean([r.helpfulness for r in sel if r.helpfulness is not None])
                if any(r.helpfulness is not None for r in sel)
                else float("nan")
            )
            reuse_mean = (
                statistics.fmean([r.reusability for r in sel if r.reusability is not None])
                if any(r.reusability is not None for r in sel)
                else float("nan")
            )
            adopt_yes = sum(1 for r in sel if r.adoption == "Yes")
            ts_vals = [r.time_saved_pct for r in sel if r.time_saved_pct is not None]
            ts_mean = statistics.fmean(ts_vals) if ts_vals else float("nan")
            row[track] = {
                "n": n,
                "help": help_mean,
                "reuse": reuse_mean,
                "adopt_yes_pct": (100 * adopt_yes / n) if n else float("nan"),
                "time_saved": ts_mean,
            }
        rows.append(row)
    return rows


def coverage_summary(responses: list[Response]) -> dict:
    evaluators = {r.evaluator for r in responses}
    patterns = {r.scenario_id for r in responses}
    by_pattern_track = Counter((r.scenario_id, r.track) for r in responses)
    return {
        "n_responses": len(responses),
        "n_evaluators": len(evaluators),
        "n_patterns": len(patterns),
        "missing_pattern_track": [
            (pid, track)
            for pid in patterns
            for track in (CREATIVITY, FUNCTIONALITY)
            if (pid, track) not in by_pattern_track
        ],
    }


