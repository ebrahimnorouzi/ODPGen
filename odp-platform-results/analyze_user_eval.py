def main() -> None:
    expert_responses = load_expert_responses()
    student_responses = load_student_responses()

    cov = coverage_summary(expert_responses)
    likert = likert_summary(expert_responses)
    mw = mann_whitney(expert_responses)
    adoption = adoption_summary(expert_responses)
    iaa_data = iaa(expert_responses)
    pp = per_pattern(expert_responses)

    # Console summary for sanity checking
    print("=== Coverage ===")
    print(json.dumps({k: v for k, v in cov.items() if k != "missing_pattern_track"}, indent=2))
    if cov["missing_pattern_track"]:
        print("Missing (pattern, track) cells:", cov["missing_pattern_track"])
    print("\n=== Likert ===")
    for dim, blocks in likert.items():
        for track, s in blocks.items():
            print(f"  {dim:14s} | {track:13s} | n={s['n']:3d} | "
                  f"mean={s['mean']:.2f} | median={s['median']:.1f} | sd={s['sd']:.2f}")
    print("\n=== Mann-Whitney U (Creativity vs Functionality) ===")
    for dim, v in mw.items():
        print(f"  {dim:14s} | U={v['U']:.1f} | p={v['p']:.4f}")
    print("\n=== Adoption / time saved ===")
    for track, a in adoption.items():
        print(
            f"  {track:14s} | Yes {a['yes']:>3} ({a['yes_pct']:.0f}%) | "
            f"Maybe {a['maybe']:>3} ({a['maybe_pct']:.0f}%) | No {a['no']:>3} "
            f"({a['no_pct']:.0f}%) | mean_ts={a['mean_time_saved']:.1f}%"
        )
    print("\n=== Krippendorff alpha ===")
    for dim, d in iaa_data.items():
        print(f"  {dim:14s} | items={d['items']:3d} | alpha={d['alpha']:.3f}")
    print(f"\n=== Students: {len(student_responses)} responses, "
          f"{len({r.evaluator for r in student_responses})} evaluators ===")

    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    PAPER_TABLES.mkdir(parents=True, exist_ok=True)

    TAB_LIKERT.write_text(_likert_table(likert, mw), encoding="utf-8")
    TAB_ADOPTION.write_text(_adoption_table(adoption), encoding="utf-8")
    TAB_IAA.write_text(_iaa_table(iaa_data), encoding="utf-8")
    TAB_PER_PATTERN.write_text(_per_pattern_table(pp), encoding="utf-8")

    section_tex = render_section(student_responses, likert, adoption, pp, cov)
    OUT_TEX.write_text(section_tex, encoding="utf-8")

    print(f"\nWrote {OUT_TEX}")
    for p in (TAB_LIKERT, TAB_ADOPTION, TAB_IAA, TAB_PER_PATTERN):
        print(f"Wrote {p}")


if __name__ == "__main__":
    main()
