"""
analyze_students_eval.py — produce a standalone supplementary report for the
student-based evaluation of LLM-generated ODPs.

Reads students-responses.csv from this directory, summarises the responses
per track (Creativity = Llama-3.1-8B / scenario-only, Functionality =
Llama-2-70B / cq-only), per student level (MSc / PhD), and per evaluated
pattern, and writes a self-contained LaTeX document to
odp-platform-results/students-evaluation.tex. The document compiles
directly to PDF (`pdflatex students-evaluation.tex`) and is intended to be
released alongside the main paper as supplementary material.

Usage:
    python3 analyze_students_eval.py
"""

from __future__ import annotations

import math
import re
import statistics
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from analyze_user_eval import (
    CREATIVITY,
    FUNCTIONALITY,
    PATTERN_TITLES,
    TIME_SAVED_MIDPOINT,
    _classify_track,
    _normalize_time_saved,
    _parse_int,
    _parse_pattern_url,
    _read_csv,
)

THIS_DIR = Path(__file__).resolve().parent
INPUT_CSV = THIS_DIR / "students-responses.csv"
OUT_TEX = THIS_DIR / "student.tex"

AUTOGEN_BANNER = (
    "% AUTO-GENERATED by odp-platform-results/analyze_students_eval.py "
    "— DO NOT EDIT MANUALLY.\n"
    "% Re-run the script after updating students-responses.csv.\n"
)


@dataclass
class StudentResponse:
    evaluator: str
    scenario_id: str
    track: str
    level: str
    time_to_understand_min: float | None
    doc_clarity: int | None
    naming_clarity: int | None
    adoption: str
    time_saved_label: str
    time_saved_pct: float | None
    justification: str


def _parse_time_to_understand(raw: str) -> float | None:
    """Pull the leading number out of free-text answers such as
    ``5'', ``5min'', ``6 (visualization tool failed)''."""
    if not raw:
        return None
    m = re.match(r"\s*([0-9]+(?:\.[0-9]+)?)", raw)
    return float(m.group(1)) if m else None


def load_students() -> list[StudentResponse]:
    out: list[StudentResponse] = []
    for row in _read_csv(INPUT_CSV):
        try:
            model, config, scen = _parse_pattern_url(row["pattern_link"])
        except (ValueError, KeyError):
            continue
        track = _classify_track(model, config)
        if track is None:
            continue
        ts_label = _normalize_time_saved(row.get("q_q_time_saved", ""))
        out.append(
            StudentResponse(
                evaluator=row["evaluator_token"],
                scenario_id=scen,
                track=track,
                level=row.get("q_q_student_level", "").strip(),
                time_to_understand_min=_parse_time_to_understand(
                    row.get("q_q_time_to_understand", "")
                ),
                doc_clarity=_parse_int(row.get("q_q_documentation_clarity", "")),
                naming_clarity=_parse_int(row.get("q_q_naming_clarity", "")),
                adoption=row.get("q_q_adoption", "").strip(),
                time_saved_label=ts_label,
                time_saved_pct=TIME_SAVED_MIDPOINT.get(ts_label),
                justification=row.get("q_q_adoption_justification", "").strip(),
            )
        )
    return out


def _mean(values: list[float | None]) -> float:
    vs = [v for v in values if v is not None]
    return statistics.fmean(vs) if vs else float("nan")


def _fmt(x: float, prec: int = 2) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.{prec}f}"


def _adoption(rows: list[StudentResponse]) -> dict:
    c = Counter(r.adoption for r in rows)
    n = sum(c.values()) or 1
    ts = [r.time_saved_pct for r in rows if r.time_saved_pct is not None]
    return {
        "yes": c.get("Yes", 0),
        "maybe": c.get("Maybe", 0),
        "no": c.get("No", 0),
        "n": sum(c.values()),
        "yes_pct": 100 * c.get("Yes", 0) / n,
        "maybe_pct": 100 * c.get("Maybe", 0) / n,
        "no_pct": 100 * c.get("No", 0) / n,
        "mean_time_saved": statistics.fmean(ts) if ts else float("nan"),
    }


def _by_track_table(rows: list[StudentResponse]) -> str:
    out = [
        "\\begin{table}[t]",
        "\\centering",
        (
            "\\caption{Student evaluation by track. Mean documentation "
            "clarity and mean naming clarity are reported on a 1--5 "
            "Likert scale; adoption percentages and mean estimated time "
            "saved (interval midpoints) are derived from the same forms.}"
        ),
        "\\label{tab:students-track}",
        "\\begin{tabular}{l c c c c c c}",
        "\\toprule",
        (
            "Track & $N$ & Doc.\\ clarity & Naming clarity & "
            "Yes\\% & Maybe\\% & Time saved \\\\"
        ),
        "\\midrule",
    ]
    for track in (CREATIVITY, FUNCTIONALITY, "Overall"):
        sel = rows if track == "Overall" else [r for r in rows if r.track == track]
        ad = _adoption(sel)
        out.append(
            f"{track} & {len(sel)} & "
            f"{_fmt(_mean([r.doc_clarity for r in sel]))} & "
            f"{_fmt(_mean([r.naming_clarity for r in sel]))} & "
            f"{_fmt(ad['yes_pct'], 0)}\\% & "
            f"{_fmt(ad['maybe_pct'], 0)}\\% & "
            f"{_fmt(ad['mean_time_saved'], 1)}\\% \\\\"
        )
        if track == FUNCTIONALITY:
            out.append("\\midrule")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out)


def _by_level_table(rows: list[StudentResponse]) -> str:
    out = [
        "\\begin{table}[t]",
        "\\centering",
        (
            "\\caption{Student evaluation by self-reported level "
            "(MSc / PhD). The mean time-to-understand is in minutes and "
            "is derived from the leading numeric value of each free-text "
            "answer.}"
        ),
        "\\label{tab:students-level}",
        "\\begin{tabular}{l c c c c c}",
        "\\toprule",
        (
            "Level & $N$ & Doc.\\ clarity & Naming clarity & "
            "Yes\\% & Time-to-understand (min) \\\\"
        ),
        "\\midrule",
    ]
    for level in ("MSc", "PhD"):
        sel = [r for r in rows if r.level == level]
        ad = _adoption(sel)
        ttu = _mean([r.time_to_understand_min for r in sel])
        out.append(
            f"{level} & {len(sel)} & "
            f"{_fmt(_mean([r.doc_clarity for r in sel]))} & "
            f"{_fmt(_mean([r.naming_clarity for r in sel]))} & "
            f"{_fmt(ad['yes_pct'], 0)}\\% & "
            f"{_fmt(ttu, 1)} \\\\"
        )
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out)


def _per_pattern_table(rows: list[StudentResponse]) -> str:
    pids = sorted({r.scenario_id for r in rows})
    out = [
        "\\begin{table}[t]",
        "\\centering",
        (
            "\\caption{Student evaluation by pattern and track. Doc.\\ "
            "clarity and Naming clarity are 1--5 Likert means; "
            "Yes\\% is the share of \\emph{Yes} adoption answers.}"
        ),
        "\\label{tab:students-pattern}",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{l c c c c | c c c c}",
        "\\toprule",
        (
            "& \\multicolumn{4}{c}{Creativity (\\textit{scenario-only})} "
            "& \\multicolumn{4}{c}{Functionality (\\textit{cq-only})} \\\\"
        ),
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9}",
        (
            "Pattern & $N$ & Doc. & Naming & Yes\\% & "
            "$N$ & Doc. & Naming & Yes\\% \\\\"
        ),
        "\\midrule",
    ]
    for pid in pids:
        crow = [r for r in rows if r.scenario_id == pid and r.track == CREATIVITY]
        frow = [r for r in rows if r.scenario_id == pid and r.track == FUNCTIONALITY]
        title = PATTERN_TITLES.get(pid, pid).replace("&", "\\&")
        ca = _adoption(crow)
        fa = _adoption(frow)
        out.append(
            f"{title} & {len(crow)} & "
            f"{_fmt(_mean([r.doc_clarity for r in crow]))} & "
            f"{_fmt(_mean([r.naming_clarity for r in crow]))} & "
            f"{_fmt(ca['yes_pct'], 0)}\\% & "
            f"{len(frow)} & "
            f"{_fmt(_mean([r.doc_clarity for r in frow]))} & "
            f"{_fmt(_mean([r.naming_clarity for r in frow]))} & "
            f"{_fmt(fa['yes_pct'], 0)}\\% \\\\"
        )
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out)


def render_document(rows: list[StudentResponse]) -> str:
    n_resp = len(rows)
    n_eval = len({r.evaluator for r in rows})
    n_patterns = len({r.scenario_id for r in rows})

    return "\n".join(
        [
            AUTOGEN_BANNER,
            "\\documentclass[11pt]{article}",
            "\\usepackage[margin=1in]{geometry}",
            "\\usepackage{booktabs}",
            "\\usepackage{hyperref}",
            "\\usepackage{enumitem}",
            "",
            "\\title{Student-based Evaluation of LLM-generated Ontology "
            "Design Patterns}",
            "\\author{Supplementary material to the ODPGen study}",
            "\\date{}",
            "",
            "\\begin{document}",
            "\\maketitle",
            "",
            "\\section*{Overview}",
            "This supplementary report summarises the student "
            "evaluation conducted alongside the main expert evaluation "
            "of LLM-generated Ontology Design Patterns (ODPs). "
            "Students were recruited from two Knowledge Engineering "
            "courses and completed a dedicated form, distinct from the "
            "expert form, which focused on aspects more relevant to "
            "less experienced users (clarity of documentation and of "
            "naming, time required to understand a draft).",
            "",
            f"A total of {n_resp} responses were collected from "
            f"{n_eval} students. Each student was randomly assigned "
            f"two of the patterns in the dataset and rated both the "
            f"Creativity-track output (\\textit{{Llama-3.1-8B}}, "
            f"\\textit{{scenario-only}}) and the Functionality-track "
            f"output (\\textit{{Llama-2-70B}}, \\textit{{cq-only}}) for "
            f"every assigned pattern, yielding four assessments per "
            f"student. The pool covers {n_patterns} of the 14 patterns "
            "in the dataset.",
            "",
            "\\section*{Question schema}",
            "Each response consisted of the following items:",
            "\\begin{itemize}[leftmargin=*]",
            "  \\item \\textbf{Student level.} Self-reported "
            "background (MSc or PhD).",
            "  \\item \\textbf{Time to understand.} Free-text answer, "
            "in minutes, for the time required to understand the "
            "generated draft.",
            "  \\item \\textbf{Documentation clarity (1--5).} Likert "
            "rating of how clear the natural-language documentation "
            "is.",
            "  \\item \\textbf{Naming clarity (1--5).} Likert rating "
            "of how clear and consistent class and property names are.",
            "  \\item \\textbf{Adoption threshold.} Whether the "
            "student would start from the generated draft "
            "(\\emph{Yes / Maybe / No}), with a brief justification.",
            "  \\item \\textbf{Time saved vs.\\ from-scratch.} "
            "Estimated proportion of time saved if the draft were used "
            "as a starting point ($0\\%$, $1$--$25\\%$, $26$--$50\\%$, "
            "$51$--$75\\%$, $76$--$100\\%$).",
            "\\end{itemize}",
            "",
            "\\section*{Results by track}",
            _by_track_table(rows),
            "",
            "Across both tracks, students rate the documentation "
            f"clarity at "
            f"{_mean([r.doc_clarity for r in rows]):.2f}/5 on average "
            f"and the naming clarity at "
            f"{_mean([r.naming_clarity for r in rows]):.2f}/5. "
            "Adoption answers are skewed towards \\emph{Maybe}, with "
            "comparatively few outright \\emph{Yes} answers.",
            "",
            "\\section*{Results by self-reported level}",
            _by_level_table(rows),
            "",
            "\\section*{Per-pattern results}",
            _per_pattern_table(rows),
            "",
            "\\section*{Note on the data}",
            "Students provided written justifications for their "
            "adoption choices. Recurring themes (missing properties, "
            "weak documentation, overly literal reuse of scenario "
            "vocabulary) align with those identified in the main "
            "expert pool and are not reproduced here. Free-text "
            "responses are not redistributed alongside this summary in "
            "order to protect respondent anonymity.",
            "",
            "\\end{document}",
        ]
    )


def main() -> None:
    rows = load_students()
    if not rows:
        raise SystemExit("No student responses found.")

    n_eval = len({r.evaluator for r in rows})
    n_patterns = len({r.scenario_id for r in rows})
    print(
        f"Loaded {len(rows)} student responses from {n_eval} students, "
        f"covering {n_patterns} patterns."
    )

    print()
    print("=== By track ===")
    for track in (CREATIVITY, FUNCTIONALITY, "Overall"):
        sel = rows if track == "Overall" else [r for r in rows if r.track == track]
        ad = _adoption(sel)
        print(
            f"  {track:13s} | n={len(sel):2d} | "
            f"doc={_mean([r.doc_clarity for r in sel]):.2f} | "
            f"naming={_mean([r.naming_clarity for r in sel]):.2f} | "
            f"Yes%={ad['yes_pct']:.0f} | "
            f"Maybe%={ad['maybe_pct']:.0f} | "
            f"TS={ad['mean_time_saved']:.1f}"
        )

    OUT_TEX.write_text(render_document(rows), encoding="utf-8")
    print(f"\nWrote {OUT_TEX}")


if __name__ == "__main__":
    main()
