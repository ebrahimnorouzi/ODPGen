"""
analyze_author_eval.py — pipeline for the pattern-author responses.

Reads the per-author CSV exports (author_<id>-responses.csv) from this
directory. Each file uses two question schemas that share the same column
layout:

* Own pattern (the author's own ODP). Populated fields:
  q_q_author_role, q_q_intent_match, q_q_scope_appropriate,
  q_q_reuse_readiness, q_q_adoption_threshold, q_q_adoption_justification,
  q_q_time_saved, q_q_missing_elements.

* Extra pattern (a random pattern, evaluated with the expert form).
  Populated fields: q_q_overall_helpfulness, q_q_reusability,
  q_q_clarity_documentation, q_q_adoption_threshold,
  q_q_adoption_justification, q_q_time_saved.

The script aggregates the two subsets by track (Creativity = Llama-3.1-8B /
scenario-only, Functionality = Llama-2-70B / cq-only) and emits two LaTeX
tables plus a short prose section.

Usage:
    python3 analyze_author_eval.py
"""

from __future__ import annotations

import math
import statistics
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from analyze_user_eval import (
    CREATIVITY,
    FUNCTIONALITY,
    PAPER_DIR,
    TIME_SAVED_MIDPOINT,
    _classify_track,
    _normalize_time_saved,
    _parse_int,
    _parse_pattern_url,
    _read_csv,
)

AUTOGEN_BANNER = (
    "% AUTO-GENERATED by odp-platform-results/analyze_author_eval.py "
    "— DO NOT EDIT MANUALLY.\n"
    "% Re-run the script after updating the CSVs in "
    "odp-platform-results/.\n"
)

THIS_DIR = Path(__file__).resolve().parent

PAPER_SECTIONS = PAPER_DIR / "sections"
PAPER_TABLES = PAPER_DIR / "tables"

OUT_TEX = PAPER_SECTIONS / "authors-evaluation.tex"
TAB_OWN = PAPER_TABLES / "tab_author_own.tex"
# The extra-pattern responses are folded into the main expert pool by
# analyze_user_eval.py, so we no longer emit a separate table for them. If
# an old file from a previous run is still present, it is removed.
TAB_EXTRA = PAPER_TABLES / "tab_author_extra.tex"

AUTHOR_CSVS = sorted(THIS_DIR.glob("author_*-responses.csv"))

# Total number of pattern-papers in the dataset for which an author form was
# created (used in the prose; matches the 10 source papers in the dataset
# table in the paper).
N_INVITATIONS_SENT = 10

# Filter out submissions that look like empty / test sessions. We treat any
# response submitted in under 30 seconds as a test/empty session; the eight
# author questions reliably take longer than that to answer.
MIN_DURATION_MS = 30_000


@dataclass
class AuthorResponse:
    evaluator: str
    scenario_id: str
    track: str
    duration_ms: int
    role: str
    # own-pattern fields
    intent: int | None
    scope: int | None
    reuse: int | None
    # extra-pattern fields
    helpfulness: int | None
    reusability: int | None
    clarity: int | None
    # shared fields
    adoption: str
    time_saved_label: str
    time_saved_pct: float | None
    justification: str
    missing_elements: str
    additional_obs: str

    @property
    def is_own_pattern(self) -> bool:
        return self.intent is not None or bool(self.role)

    @property
    def looks_genuine(self) -> bool:
        return self.duration_ms >= MIN_DURATION_MS


def load_author_responses() -> list[AuthorResponse]:
    out: list[AuthorResponse] = []
    for path in AUTHOR_CSVS:
        for row in _read_csv(path):
            try:
                model, config, scen = _parse_pattern_url(row["pattern_link"])
            except (ValueError, KeyError):
                continue
            track = _classify_track(model, config)
            if track is None:
                continue
            try:
                duration = int(row.get("duration_ms", "0") or 0)
            except ValueError:
                duration = 0
            ts_label = _normalize_time_saved(row.get("q_q_time_saved", ""))
            out.append(
                AuthorResponse(
                    evaluator=row["evaluator_token"],
                    scenario_id=scen,
                    track=track,
                    duration_ms=duration,
                    role=row.get("q_q_author_role", "").strip(),
                    intent=_parse_int(row.get("q_q_intent_match", "")),
                    scope=_parse_int(row.get("q_q_scope_appropriate", "")),
                    reuse=_parse_int(row.get("q_q_reuse_readiness", "")),
                    helpfulness=_parse_int(row.get("q_q_overall_helpfulness", "")),
                    reusability=_parse_int(row.get("q_q_reusability", "")),
                    clarity=_parse_int(row.get("q_q_clarity_documentation", "")),
                    adoption=row.get("q_q_adoption_threshold", "").strip(),
                    time_saved_label=ts_label,
                    time_saved_pct=TIME_SAVED_MIDPOINT.get(ts_label),
                    justification=row.get("q_q_adoption_justification", "").strip(),
                    missing_elements=row.get("q_q_missing_elements", "").strip(),
                    additional_obs=row.get("q_q_additional_observations", "").strip(),
                )
            )
    return out


def _stats(values: list[float | None]) -> dict[str, float | int]:
    vals = [v for v in values if v is not None]
    if not vals:
        return {"n": 0, "mean": float("nan")}
    return {
        "n": len(vals),
        "mean": statistics.fmean(vals),
    }


def _adoption_dist(rows: list[AuthorResponse]) -> dict[str, int | float]:
    c = Counter(r.adoption for r in rows)
    n = sum(c.values()) or 1
    ts = [r.time_saved_pct for r in rows if r.time_saved_pct is not None]
    return {
        "yes": c.get("Yes", 0),
        "maybe": c.get("Maybe", 0),
        "no": c.get("No", 0),
        "n": sum(c.values()),
        "yes_pct": 100 * c.get("Yes", 0) / n,
        "mean_time_saved": statistics.fmean(ts) if ts else float("nan"),
    }


def _fmt(x: float, prec: int = 2) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.{prec}f}"


def _own_table(own: list[AuthorResponse]) -> str:
    rows: list[str] = [
        AUTOGEN_BANNER,
        "\\begin{table}[t]",
        "\\centering",
        (
            "\\caption{Pattern-author evaluation of their own pattern, "
            "by track. Intent, scope, and reuse are 1--5 Likert scales "
            "(higher is better); Yes\\% is the share of \\emph{Yes} "
            "adoption answers; Time saved uses the interval midpoints.}"
        ),
        "\\label{tab:author-own}",
        "\\small",
        "\\begin{tabular}{l c c c c c c}",
        "\\toprule",
        (
            "Track & $N$ & Intent & Scope & Reuse & Yes\\% & Time saved \\\\"
        ),
        "\\midrule",
    ]
    for track in (CREATIVITY, FUNCTIONALITY):
        sel = [r for r in own if r.track == track]
        n = len(sel)
        intent = _stats([r.intent for r in sel])
        scope = _stats([r.scope for r in sel])
        reuse = _stats([r.reuse for r in sel])
        ad = _adoption_dist(sel)
        rows.append(
            f"{track} & {n} & {_fmt(intent['mean'])} & "
            f"{_fmt(scope['mean'])} & {_fmt(reuse['mean'])} & "
            f"{_fmt(ad['yes_pct'], 0)}\\% & "
            f"{_fmt(ad['mean_time_saved'], 1)}\\% \\\\"
        )
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(rows)


def render_section(
    own: list[AuthorResponse],
    n_dropped: int,
) -> str:
    n_own = len(own)
    n_eval = len({r.evaluator for r in own})
    n_patterns_own = len({r.scenario_id for r in own})

    own_yes = sum(1 for r in own if r.adoption == "Yes")
    own_intent_means = [
        statistics.fmean([r.intent for r in own if r.track == t and r.intent is not None] or [float("nan")])
        for t in (CREATIVITY, FUNCTIONALITY)
    ]

    drop_clause = (
        f", after {n_dropped} short test responses were discarded"
        if n_dropped
        else ""
    )

    body = [
        AUTOGEN_BANNER,
        (
            "Each author of an ODP in our dataset was invited to "
            "evaluate the LLM-generated drafts of their own pattern, "
            "and to provide an additional evaluation of one randomly "
            "assigned pattern from the dataset. The latter was answered "
            "with the standard expert questionnaire, and those responses "
            "have therefore been folded into the expert pool reported in "
            "Section~\\ref{sec:expert-results}; here we report only the "
            "author-specific assessment of their own pattern. Of the "
            f"{N_INVITATIONS_SENT} pattern-papers in the dataset, the "
            f"authors of {n_patterns_own} patterns responded "
            f"({n_eval} respondents in total{drop_clause}). "
            "Table~\\ref{tab:author-own} reports how faithfully the "
            "drafts capture the original modelling intent, whether the "
            "scope is appropriate, and how ready they are for reuse."
        ),
        "",
        "\\input{tables/tab_author_own}",
        "",
        (
            f"Across the {n_own} own-pattern responses, the scores are "
            f"uniformly low (mean intent "
            f"{own_intent_means[0]:.1f}/5 for the Creativity track and "
            f"{own_intent_means[1]:.1f}/5 for the Functionality track), "
            f"and {own_yes} of the {n_own} responses indicate "
            "willingness to adopt the draft as a starting point. Given "
            "the very small sample, these numbers are best read as "
            "illustrative rather than as a quantitative claim. The "
            "qualitative comments converge on the same themes discussed "
            "in Section~\\ref{sec:recommendations} --- missing "
            "properties, weak documentation, and over-literal reuse of "
            "scenario vocabulary --- and are therefore not repeated here."
        ),
        "",
    ]
    return "\n".join(body)


def main() -> None:
    raw = load_author_responses()
    genuine = [r for r in raw if r.looks_genuine]
    n_dropped = len(raw) - len(genuine)

    own = [r for r in genuine if r.is_own_pattern]
    extra = [r for r in genuine if not r.is_own_pattern]

    print(f"Loaded {len(raw)} author responses; {n_dropped} dropped as "
          "short/test sessions.")
    print(f"  Own-pattern responses: {len(own)} "
          f"(patterns: {sorted({r.scenario_id for r in own})})")
    print(f"  Extra-pattern responses (folded into expert pool by "
          f"analyze_user_eval.py): {len(extra)}")
    print()

    print("=== Own pattern by track ===")
    for track in (CREATIVITY, FUNCTIONALITY):
        sel = [r for r in own if r.track == track]
        n = len(sel)
        intent = _stats([r.intent for r in sel])
        scope = _stats([r.scope for r in sel])
        reuse = _stats([r.reuse for r in sel])
        ad = _adoption_dist(sel)
        print(
            f"  {track:13s} | n={n:2d} | intent={intent['mean']:.2f} "
            f"| scope={scope['mean']:.2f} | reuse={reuse['mean']:.2f} "
            f"| Yes%={ad['yes_pct']:.0f} | TS={ad['mean_time_saved']:.1f}"
        )

    PAPER_SECTIONS.mkdir(parents=True, exist_ok=True)
    PAPER_TABLES.mkdir(parents=True, exist_ok=True)

    TAB_OWN.write_text(_own_table(own), encoding="utf-8")
    OUT_TEX.write_text(
        render_section(own, n_dropped),
        encoding="utf-8",
    )

    # Remove the stale extra-pattern table from a previous run, if any.
    if TAB_EXTRA.exists():
        TAB_EXTRA.unlink()

    print()
    print(f"Wrote {OUT_TEX}")
    print(f"Wrote {TAB_OWN}")


if __name__ == "__main__":
    main()
